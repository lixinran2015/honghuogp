"""
验证 sz.000516 是否破均线
对比不同容忍度的判定结果
"""
import pandas as pd

# sz.000516 在 2025-10-31 的实际数据（从终端输出复制）
data = {
    'time': ['20251031093500000', '20251031094000000', '20251031094500000', '20251031095000000',
             '20251031095500000', '20251031100000000', '20251031100500000', '20251031101000000'],
    'low': [4.76, 4.77, 4.76, 4.76, 4.77, 4.76, 4.76, 4.76],
    'ma': [4.766656, 4.768712, 4.769097, 4.768638, 4.769000, 4.769010, 4.768689, 4.768747],
}

df = pd.DataFrame(data)
df['diff'] = df['low'] - df['ma']

print("=" * 70)
print("📊 sz.000516 破均线验证")
print("=" * 70)
print("\n前 8 条数据（已显示破均线情况）：\n")
print(df.to_string(index=True))

print("\n" + "=" * 70)
print("🔍 不同容忍度的判定结果")
print("=" * 70)

tolerances = [0, 0.001, 0.005, 0.01, 0.02]

for tol in tolerances:
    broke = (df['diff'] < -tol).any()
    min_diff = df['diff'].min()
    count_broke = (df['diff'] < -tol).sum()
    
    status = "❌ 破均线" if broke else "✅ 未破均线"
    
    print(f"\n容忍度 = {tol:.3f} 元:")
    print(f"  判定结果: {status}")
    print(f"  最小差值: {min_diff:.6f} 元")
    print(f"  破均线次数: {count_broke} 次 (在前8条中)")
    
    if tol == 0.001:
        print(f"  👉 当前使用的容忍度")
    elif tol == 0.01:
        print(f"  ⚠️  旧版本使用的容忍度（过于宽松）")

print("\n" + "=" * 70)
print("💡 结论")
print("=" * 70)
print("• 旧容忍度 (0.01元): 判定为'未破均线' ❌ 错误！")
print("• 新容忍度 (0.001元): 判定为'破均线' ✅ 正确！")
print("\n对于 4.77 元的股票：")
print("  • 0.01 元容忍度 ≈ 0.21% (太宽松)")
print("  • 0.001 元容忍度 ≈ 0.021% (合理)")
print("\n📈 建议: 使用 0.001 元作为容忍度，既能容忍微小的计算误差，")
print("         又能准确识别真正破均线的情况。")
print("=" * 70)

